#!/usr/bin/env python3
"""Build the SP1 guests reproducibly and record their program keys.

Every guest is built with `cargo prove build --docker` in the SP1 image pinned below. The
repository is mounted at the same container path for every build, so program keys do not
depend on the checkout path. Requires cargo-prove 6.10.0 and Docker.

    python3 scripts/build_sp1_guests.py [--citrea DIR] [--guest {header-chain,work-only,bridge-circuit}]

`--citrea DIR` records the program keys of Citrea's light client ELFs
(`<network>-light-client.elf`), which the bridge guest embeds. Build the bridge guest after the
header-chain and work-only guests, because it embeds their keys too.
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ELFS = ROOT / "sp1-circuits/elfs"
MANIFEST = ELFS / "manifest.json"
TABLE = ROOT / "circuits-lib/src/common/sp1_programs.rs"
SP1_VERSION = "6.10.0"
# ghcr.io/succinctlabs/sp1:v6.10.0
SP1_IMAGE = "ghcr.io/succinctlabs/sp1@sha256:9363a70004271de441e863612c7aefbbc5c36f371f111cd8abb1672fa5ea99f1"
NETWORKS = ["mainnet", "testnet4", "signet", "regtest"]
GUESTS = ["header-chain", "work-only", "bridge-circuit"]


def program_key(elf: Path) -> str:
    output = subprocess.check_output(["cargo", "prove", "vkey", "--elf", str(elf)], text=True)
    return re.search(r"^0x([0-9a-f]{64})$", output, re.M).group(1)


def record(manifest: dict, name: str, elf: Path) -> None:
    manifest[name] = {
        "program_key": program_key(elf),
        "sha256": hashlib.sha256(elf.read_bytes()).hexdigest(),
        "sp1_version": SP1_VERSION,
    }
    print(f"{name}: {manifest[name]['program_key']}", flush=True)


def build(guest: str, network: str, development: bool) -> Path:
    """Builds one guest ELF for `network`; the development build verifies watchtower
    proofs with the development key."""
    name = f"{'test-' if development else ''}{network}-{guest}"
    command = [
        "cargo", "prove", "build", "--docker", "--locked",
        "--workspace-directory", str(ROOT),
        "--output-directory", str(ELFS),
        "--elf-name", f"{name}.elf",
        # `cargo prove build --docker` does not forward environment variables. The guests read
        # the network with `option_env!("BITCOIN_NETWORK")` at compile time.
        f"--rustflags=-Zunstable-options,--env-set,BITCOIN_NETWORK={network}",
    ]
    if development:
        command += ["--features", "testing"]
    env = dict(os.environ, SP1_DOCKER_IMAGE=SP1_IMAGE)
    env.pop("CARGO_TARGET_DIR", None)
    subprocess.run(command, cwd=ROOT / "sp1-circuits" / guest, env=env, check=True)
    return ELFS / f"{name}.elf"


def key_literal(manifest: dict, name: str) -> str:
    # Unpack the CLI's canonical BN254 program identifier once, during artifact generation.
    # Guests use these native words directly; no runtime or const-eval conversion is needed.
    encoded = bytes.fromhex(manifest[name]["program_key"])
    value = int.from_bytes(encoded, "big")
    words = [(value >> (31 * i)) & 0x7fffffff for i in reversed(range(8))]
    assert value < 1 << 248 and all(word < 0x7f000001 for word in words)
    return f"ProgramKey {{ recursion: {words}, groth16: {list(encoded)} }}"


def write_table(manifest: dict) -> None:
    lines = [
        "// Generated by scripts/build_sp1_guests.py from sp1-circuits/elfs/manifest.json.",
        "use super::programs::{NetworkPrograms, ProgramKey};",
        "",
    ]
    for network in NETWORKS:
        lines += [
            "#[rustfmt::skip]",
            f"pub const {network.upper()}: NetworkPrograms = NetworkPrograms {{",
            f"    header_chain: {key_literal(manifest, f'{network}-header-chain')},",
            f"    work_only: {key_literal(manifest, f'{network}-work-only')},",
            f"    bridge: {key_literal(manifest, f'{network}-bridge-circuit')},",
            f"    light_client: {key_literal(manifest, f'{network}-light-client')},",
            "};",
        ]
    lines += ["", "/// Bridge guests built with `testing`, which verify watchtower proofs with the development key."]
    for network in NETWORKS[1:]:
        lines += [
            "#[rustfmt::skip]",
            f"pub const {network.upper()}_DEVELOPMENT_BRIDGE: ProgramKey = "
            f"{key_literal(manifest, f'test-{network}-bridge-circuit')};",
        ]
    TABLE.write_text("\n".join(lines) + "\n")


def save(manifest: dict) -> None:
    MANIFEST.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    write_table(manifest)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--citrea", type=Path, help="directory with Citrea's light client ELFs")
    parser.add_argument("--guest", choices=GUESTS, action="append", help="guests to build (default: all)")
    args = parser.parse_args()

    manifest = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    artifacts = {f"{network}-{kind}" for network in NETWORKS for kind in GUESTS + ["light-client"]}
    artifacts |= {f"test-{network}-bridge-circuit" for network in NETWORKS[1:]}
    manifest = {name: entry for name, entry in manifest.items() if name in artifacts}
    if args.citrea:
        for network in NETWORKS:
            record(manifest, f"{network}-light-client", args.citrea / f"{network}-light-client.elf")
        # The bridge guest embeds these keys from the table, so write it before building.
        save(manifest)

    for guest in args.guest or GUESTS:
        for network in NETWORKS:
            record(manifest, f"{network}-{guest}", build(guest, network, development=False))
            if guest == "bridge-circuit" and network != "mainnet":
                record(manifest, f"test-{network}-{guest}", build(guest, network, development=True))
            save(manifest)


if __name__ == "__main__":
    main()
